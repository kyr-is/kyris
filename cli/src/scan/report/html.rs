#[cfg(test)]
mod tests {
    use super::*;
    use crate::scan::scanner::{FindingCategory, FindingLocation};

    fn make_finding(severity: Severity, category: FindingCategory) -> Finding {
        Finding {
            category,
            severity,
            title: "Test <finding> & check".to_string(),
            description: "A \"description\" with 'quotes'.".to_string(),
            location: FindingLocation {
                path: "/path/to/file.rs".to_string(),
                line: Some(42),
            },
            evidence: Some("sk-ant-abc123...".to_string()),
            remediation: "Fix it now.".to_string(),
        }
    }

    #[test]
    fn testBuildHtmlIsValidHtml() {
        let html = build_html(&[]);
        assert!(html.starts_with("<!DOCTYPE html>"));
        assert!(html.contains("<html"));
        assert!(html.contains("</html>"));
        assert!(html.contains("</head>"));
        assert!(html.contains("</body>"));
    }

    #[test]
    fn testBuildHtmlContainsTitleAndTimestamp() {
        let html = build_html(&[]);
        assert!(html.contains("Kyris Security Scan Report"));
        assert!(html.contains("UTC")); // timestamp always ends in UTC
    }

    #[test]
    fn testBuildHtmlContainsCta() {
        let html = build_html(&[]);
        assert!(html.contains("kyris.app"));
        assert!(html.contains("Kyris App"));
    }

    #[test]
    fn testBuildHtmlNoFindingsShowsCleanBanner() {
        let html = build_html(&[]);
        assert!(html.contains("No findings detected"));
        // No category section divs (the CSS class exists but no div should use it).
        assert!(!html.contains(r#"class="cat-hdr""#));
    }

    #[test]
    fn testBuildHtmlNoFindingsChartIsGreenClean() {
        let html = build_html(&[]);
        assert!(html.contains("Clean")); // empty-state donut label
        assert!(html.contains("#dcfce7")); // green track colour
    }

    #[test]
    fn testBuildHtmlWithFindingsShowsFindings() {
        let findings = vec![
            make_finding(Severity::Critical, FindingCategory::ApiKey),
            make_finding(Severity::High, FindingCategory::LlmTraffic),
        ];
        let html = build_html(&findings);
        assert!(!html.contains("No findings detected"));
        assert!(html.contains("CRITICAL"));
        assert!(html.contains("HIGH"));
        assert!(html.contains("API Keys"));
        assert!(html.contains("LLM Traffic"));
    }

    #[test]
    fn testBuildHtmlEscapesSpecialChars() {
        let html = build_html(&[make_finding(Severity::Info, FindingCategory::ApiKey)]);
        assert!(html.contains("Test &lt;finding&gt; &amp; check"));
        assert!(html.contains("&quot;description&quot;"));
        assert!(html.contains("it&#39;s") || html.contains("&#39;")); // single quote escaped
    }

    #[test]
    fn testBuildHtmlShowsLineNumber() {
        let html = build_html(&[make_finding(Severity::High, FindingCategory::ApiKey)]);
        assert!(html.contains("file.rs:42"));
    }

    #[test]
    fn testBuildHtmlScoreAndLevel() {
        let findings = vec![make_finding(Severity::Critical, FindingCategory::ApiKey)];
        let html = build_html(&findings);
        assert!(html.contains(">10<")); // risk score
        assert!(html.contains("CRITICAL"));
    }

    #[test]
    fn testBuildHtmlFindingCountPlural() {
        let html = build_html(&[
            make_finding(Severity::High, FindingCategory::ApiKey),
            make_finding(Severity::High, FindingCategory::ApiKey),
        ]);
        assert!(html.contains("2 findings"));
    }

    #[test]
    fn testBuildHtmlFindingCountSingular() {
        let html = build_html(&[make_finding(Severity::High, FindingCategory::ApiKey)]);
        // "1 finding" must appear (without trailing 's') somewhere in the html
        assert!(html.contains("1 finding"));
    }

    #[test]
    fn testBuildHtmlIsSelfContained() {
        let html = build_html(&[make_finding(Severity::High, FindingCategory::ApiKey)]);
        assert!(!html.contains("<link")); // no external stylesheet
        assert!(!html.contains("<script")); // no script tags
        assert!(!html.contains("src=")); // no external src references
    }

    #[test]
    fn testBuildHtmlOnlyExternalHrefIsKyrisApp() {
        let html = build_html(&[make_finding(Severity::High, FindingCategory::ApiKey)]);
        // The only http/https href must be kyris.app.
        for href in html.split("href=\"") {
            let url = href.split('"').next().unwrap_or("");
            if url.starts_with("http") {
                assert!(
                    url.starts_with("https://kyris.app"),
                    "unexpected external href: {url}"
                );
            }
        }
    }

    #[test]
    fn testBuildHtmlGroupsByCategory() {
        let findings = vec![
            make_finding(Severity::Critical, FindingCategory::ApiKey),
            make_finding(Severity::High, FindingCategory::UngoverndAgent),
        ];
        let html = build_html(&findings);
        assert!(html.contains("API Keys"));
        assert!(html.contains("Ungoverned Agents"));
    }

    #[test]
    fn testBuildHtmlOmitsEmptyCategories() {
        let findings = vec![make_finding(Severity::Critical, FindingCategory::ApiKey)];
        let html = build_html(&findings);
        assert!(!html.contains("Ungoverned Agents"));
        assert!(!html.contains("LLM Traffic"));
    }

    #[test]
    fn testDonutSvgEmpty() {
        let svg = donut_svg(&[]);
        assert!(svg.contains("<svg"));
        assert!(svg.contains("Clean"));
        assert!(svg.contains("#dcfce7"));
    }

    #[test]
    fn testDonutSvgWithFindings() {
        let findings = vec![
            make_finding(Severity::Critical, FindingCategory::ApiKey),
            make_finding(Severity::High, FindingCategory::ApiKey),
        ];
        let svg = donut_svg(&findings);
        assert!(svg.contains(CRITICAL_COLOR));
        assert!(svg.contains(HIGH_COLOR));
        assert!(svg.contains(">2<") || svg.contains(">2\n") || svg.contains("2</text>"));
    }

    #[test]
    fn testDonutSvgSegmentCount() {
        // Only non-zero severities should produce a segment circle.
        let findings = vec![make_finding(Severity::Critical, FindingCategory::ApiKey)];
        let svg = donut_svg(&findings);
        // One background track + one red segment = exactly 2 <circle> elements.
        assert_eq!(svg.matches("<circle").count(), 2);
    }

    #[test]
    fn testLegendHidesZeroSeverities() {
        let findings = vec![make_finding(Severity::Critical, FindingCategory::ApiKey)];
        let html = legend_html(&findings);
        assert!(html.contains("Critical"));
        assert!(!html.contains("High")); // zero — must not appear
        assert!(!html.contains("Info"));
    }

    #[test]
    fn testHtmlEscapeAllSpecialChars() {
        assert_eq!(he("a&b"), "a&amp;b");
        assert_eq!(he("<tag>"), "&lt;tag&gt;");
        assert_eq!(he("\"hi\""), "&quot;hi&quot;");
        assert_eq!(he("it's"), "it&#39;s");
        assert_eq!(he("plain"), "plain");
    }

    #[test]
    fn testEvidenceRowPresentWhenProvided() {
        let html = build_html(&[make_finding(Severity::High, FindingCategory::ApiKey)]);
        assert!(html.contains("class=\"ev\""));
        assert!(html.contains("sk-ant-abc123"));
    }

    #[test]
    fn testNoEvidenceRowWhenAbsent() {
        let mut f = make_finding(Severity::High, FindingCategory::ApiKey);
        f.evidence = None;
        let html = build_html(&[f]);
        assert!(!html.contains("class=\"ev\""));
    }
}
