//! Self-contained HTML scan report with inline SVG severity donut chart.
//! No external assets — the output file opens in any browser with no network.

use std::fmt::Write as _;

use crate::scan::scanner::{Finding, FindingCategory, RiskLevel, Severity, risk_level};

const CRITICAL_COLOR: &str = "#dc2626";
const HIGH_COLOR: &str = "#ea580c";
const MEDIUM_COLOR: &str = "#d97706";
const LOW_COLOR: &str = "#2563eb";
const INFO_COLOR: &str = "#6b7280";

/// Builds the complete self-contained HTML string. Exposed so `mod.rs` can
/// write it directly to a file when `--output PATH` is provided.
pub fn build_html(findings: &[Finding]) -> String {
    let timestamp = now_utc();
    let total = findings.len();
    let score: u32 = findings.iter().map(|f| f.severity as u32).sum();
    let level = risk_level(score);
    let (level_color, level_label) = level_appearance(level);
    let plural = if total == 1 { "" } else { "s" };

    let chart = donut_svg(findings);
    let legend = legend_html(findings);
    let findings_body = findings_html(findings);
    let css = css();

    let clean_banner = if total == 0 {
        r#"<div class="clean">&#10003; No findings detected &mdash; environment looks good.</div>"#
    } else {
        ""
    };

    format!(
        r#"<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width,initial-scale=1.0">
<title>Kyris Security Scan Report</title>
<style>{css}</style>
</head>
<body>
<header>
<div class="inner">
<div class="logo">Kyris</div>
<h1>Security Scan Report</h1>
<p class="ts">Generated {timestamp}</p>
</div>
</header>
<main class="inner">
<section class="summary">
<div class="risk-card" style="border-top:4px solid {level_color}">
<div class="big-score" style="color:{level_color}">{score}</div>
<div class="level-lbl" style="color:{level_color}">{level_label}</div>
<div class="sub">risk score</div>
<hr>
<div class="count">{total} finding{plural}</div>
</div>
<div class="chart-card">
{chart}
{legend}
</div>
</section>
{clean_banner}
{findings_body}
<section class="cta">
<h2>Govern your AI agents at scale</h2>
<p>Kyris App adds policy sync, spend enforcement, team visibility, and approval workflows &mdash; built on the same open-source governance engine.</p>
<a href="https://kyris.app" class="cta-btn">Try Kyris App &#x2192;</a>
</section>
</main>
<footer>Generated by <a href="https://kyris.app">Kyris</a> &middot; Open-source AI governance</footer>
</body>
</html>"#
    )
}

// ---------------------------------------------------------------------------
// SVG donut chart
//
// Note: SVG attributes like stroke="#e2e8f0" contain the sequence `"#` which
// would prematurely terminate r#"..."# raw strings. Use r##"..."## for any
// format! string that embeds literal hex colours as attribute values.
// ---------------------------------------------------------------------------

fn donut_svg(findings: &[Finding]) -> String {
    let cx = 90.0f64;
    let cy = 90.0f64;
    let r = 62.0f64;
    let sw = 26.0f64;
    let circ = 2.0 * std::f64::consts::PI * r; // ≈ 389.56

    if findings.is_empty() {
        // r## avoids the "# termination problem with fill="#166534" etc.
        return format!(
            r##"<svg viewBox="0 0 180 180" width="150" height="150" xmlns="http://www.w3.org/2000/svg"><circle cx="{cx}" cy="{cy}" r="{r}" fill="none" stroke="#dcfce7" stroke-width="{sw}"/><text x="{cx}" y="{cy}" text-anchor="middle" dominant-baseline="central" font-size="13" fill="#166534" font-weight="600">Clean</text></svg>"##
        );
    }

    let total = findings.len();

    // Open tag — no hex colours, r# is fine.
    let mut svg = String::from(
        r#"<svg viewBox="0 0 180 180" width="150" height="150" xmlns="http://www.w3.org/2000/svg">"#,
    );

    // Background track — r## because stroke="#e2e8f0" contains "# .
    let _ = write!(
        svg,
        r##"<circle cx="{cx}" cy="{cy}" r="{r}" fill="none" stroke="#e2e8f0" stroke-width="{sw}"/>"##
    );

    // Coloured segments. `color` is a variable so the template itself has no
    // literal "# — escaped-quote style keeps things simple.
    let segments = [
        (count_sev(findings, Severity::Critical), CRITICAL_COLOR),
        (count_sev(findings, Severity::High), HIGH_COLOR),
        (count_sev(findings, Severity::Medium), MEDIUM_COLOR),
        (count_sev(findings, Severity::Low), LOW_COLOR),
        (count_sev(findings, Severity::Info), INFO_COLOR),
    ];

    // stroke-dashoffset = circ − cumulative_start positions each segment
    // exactly after the previous one. rotate(-90) moves origin to 12 o'clock.
    let mut cumulative = 0.0f64;
    for (count, color) in &segments {
        if *count == 0 {
            continue;
        }
        // Severity slice counts and total are small (always under a million);
        // casting to f64 here loses no precision in any practical scan run.
        #[allow(clippy::cast_precision_loss)]
        let frac = *count as f64 / total as f64;
        let dash = frac * circ;
        let gap = circ - dash;
        let offset = circ - cumulative;
        let _ = write!(
            svg,
            "<circle cx=\"{cx}\" cy=\"{cy}\" r=\"{r}\" fill=\"none\" \
             stroke=\"{color}\" stroke-width=\"{sw}\" \
             stroke-dasharray=\"{dash:.2} {gap:.2}\" \
             stroke-dashoffset=\"{offset:.2}\" \
             transform=\"rotate(-90 {cx} {cy})\"/>"
        );
        cumulative += dash;
    }

    // Centre labels — r## because fill="#1e293b" and fill="#64748b" contain "#.
    let y1 = cy - 8.0;
    let y2 = cy + 12.0;
    let _ = write!(
        svg,
        r##"<text x="{cx}" y="{y1}" text-anchor="middle" dominant-baseline="central" font-size="22" fill="#1e293b" font-weight="700">{total}</text><text x="{cx}" y="{y2}" text-anchor="middle" font-size="9" fill="#64748b">findings</text></svg>"##
    );

    svg
}

// ---------------------------------------------------------------------------
// Severity legend
// ---------------------------------------------------------------------------

fn legend_html(findings: &[Finding]) -> String {
    let rows = [
        (
            "Critical",
            CRITICAL_COLOR,
            count_sev(findings, Severity::Critical),
        ),
        ("High", HIGH_COLOR, count_sev(findings, Severity::High)),
        (
            "Medium",
            MEDIUM_COLOR,
            count_sev(findings, Severity::Medium),
        ),
        ("Low", LOW_COLOR, count_sev(findings, Severity::Low)),
        ("Info", INFO_COLOR, count_sev(findings, Severity::Info)),
    ];
    let mut html = String::from(r#"<div class="legend">"#);
    for (label, color, count) in &rows {
        if *count == 0 {
            continue;
        }
        let _ = write!(
            html,
            r#"<div class="legend-row"><span class="dot" style="background:{color}"></span><span class="lbl">{label}</span><span class="cnt">{count}</span></div>"#
        );
    }
    html.push_str("</div>");
    html
}

// ---------------------------------------------------------------------------
// Findings grouped by category
// ---------------------------------------------------------------------------

fn findings_html(findings: &[Finding]) -> String {
    if findings.is_empty() {
        return String::new();
    }
    let categories = [
        (FindingCategory::ApiKey, "API Keys"),
        (FindingCategory::UngoverndAgent, "Ungoverned Agents"),
        (
            FindingCategory::DegradedAgent,
            "Degraded Agent Integrations",
        ),
        (FindingCategory::VendorNativeAgent, "Vendor-Governed Agents"),
        (FindingCategory::UngoverndMcp, "Ungoverned MCP Servers"),
        (FindingCategory::LlmTraffic, "LLM Traffic"),
    ];
    let mut html = String::new();
    for (cat, label) in &categories {
        let group: Vec<&Finding> = findings.iter().filter(|f| f.category == *cat).collect();
        if group.is_empty() {
            continue;
        }
        let n = group.len();
        let plural = if n == 1 { "" } else { "s" };
        let _ = write!(
            html,
            r#"<div class="cat"><div class="cat-hdr"><span>{label}</span><span>{n} finding{plural}</span></div>"#
        );
        for f in &group {
            html.push_str(&finding_html(f));
        }
        html.push_str("</div>");
    }
    html
}

fn finding_html(f: &Finding) -> String {
    let (sev_color, sev_label) = sev_appearance(f.severity);
    let loc = match f.location.line {
        Some(l) => format!("{}:{l}", he(&f.location.path)),
        None => he(&f.location.path),
    };
    let evidence_row = match &f.evidence {
        Some(ev) => format!(
            r#"<div class="meta-row"><span class="meta-lbl">Evidence</span><code class="ev">{}</code></div>"#,
            he(ev)
        ),
        None => String::new(),
    };
    format!(
        r#"<div class="finding"><div class="f-hdr"><span class="badge" style="background:{sev_color}">{sev_label}</span><span class="f-title">{}</span></div><div class="f-desc">{}</div><div class="f-meta"><div class="meta-row"><span class="meta-lbl">Location</span><code class="loc">{loc}</code></div>{evidence_row}<div class="meta-row"><span class="meta-lbl">Fix</span><span class="fix">{}</span></div></div></div>"#,
        he(&f.title),
        he(&f.description),
        he(&f.remediation),
    )
}

// ---------------------------------------------------------------------------
// Helpers
// ---------------------------------------------------------------------------

fn count_sev(findings: &[Finding], s: Severity) -> usize {
    findings.iter().filter(|f| f.severity == s).count()
}

fn sev_appearance(s: Severity) -> (&'static str, &'static str) {
    match s {
        Severity::Critical => (CRITICAL_COLOR, "CRITICAL"),
        Severity::High => (HIGH_COLOR, "HIGH"),
        Severity::Medium => (MEDIUM_COLOR, "MEDIUM"),
        Severity::Low => (LOW_COLOR, "LOW"),
        Severity::Info => (INFO_COLOR, "INFO"),
    }
}

fn level_appearance(l: RiskLevel) -> (&'static str, &'static str) {
    match l {
        RiskLevel::Critical => (CRITICAL_COLOR, "CRITICAL"),
        RiskLevel::High => (HIGH_COLOR, "HIGH"),
        RiskLevel::Medium => (MEDIUM_COLOR, "MEDIUM"),
        RiskLevel::Low => ("#16a34a", "LOW"),
    }
}

/// HTML-escapes the five special characters. No external crate needed.
fn he(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for c in s.chars() {
        match c {
            '&' => out.push_str("&amp;"),
            '<' => out.push_str("&lt;"),
            '>' => out.push_str("&gt;"),
            '"' => out.push_str("&quot;"),
            '\'' => out.push_str("&#39;"),
            c => out.push(c),
        }
    }
    out
}

fn now_utc() -> String {
    chrono::Utc::now().format("%Y-%m-%d %H:%M UTC").to_string()
}

